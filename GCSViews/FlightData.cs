                if (tabQuickDetached) MainV2.comPort.MAV.cs.UpdateCurrentSettings(bindingSourceQuickTab.UpdateDataSource(MainV2.comPort.MAV.cs));

                lastscreenupdate = DateTime.UtcNow;
            }
            catch (Exception ex)
