                gotohere.id = (ushort) MAVLink.MAV_CMD.WAYPOINT;
                gotohere.alt = MainV2.comPort.MAV.GuidedMode.z; // back to m
                gotohere.lat = (plla.Lat);
                gotohere.lng = (plla.Lng);
